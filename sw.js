// [UNIVERSAL PWA SERVICE WORKER ENGINE] ---------💮💮💮---------
// Универсальный Service Worker для Offline-first веб-приложений.
// 
// Ключевые фичи:
// -> Кэширование файлов приложения для работы без интернета
// -> Мгновенное фоновое обновление открытого приложения
//    без ручной перезагрузки (skipWaiting + clients.claim)
// -> Автоматическая очистка устаревшего кэша приложения
// -> Защита от конфликтов кэша нескольких PWA на одном домене,
//    безопасно для хостингов вроде GitHub Pages
// ---------------------------------------------------------------

// Уникальный префикс проекта, чтобы кэш не конфликтовал с другими PWA на одном домене, например GitHub Pages.
const CACHE_PREFIX = 'yes';
// Текущая версия кэша. При любом изменении файлов приложения меняй '-v1' на '-v2', '-v3' и т.д,
// чтобы у пользователей подтянулись обновлённые файлы, а старый кэш автоматически удалился.
const CACHE_NAME = `${CACHE_PREFIX}-v10`;
// Список файлов, которые нужно закэшировать при первом запуске или при выходе обновлений.
// Это App Shell(«оболочка» приложения): HTML, CSS, JS, данные(JSON и т.д.), шрифты, картинки и иконки.
// Без этих файлов приложение не сможет работать офлайн.
const ASSETS = [
  './',
  './index.html',
  './main.css',
  './icon-192x192.png',
  './icon-512x512.png'
];

/* ===========================💮💮💮=========================== */
// Событие 'install' - срабатывает при первой установке воркера,
// а также каждый раз при обнаружении обновлений в файле sw.js.
// Оно запускается браузером для НОВОГО воркера.
// ---------------------------------------------------------------
self.addEventListener('install', (event) => {
  console.log('[Service Worker] Начало установки (Install)...');
  // event.waitUntil() - говорит браузеру: «подожди, пока я закончу,
  // не активируй новый воркер раньше времени»
  event.waitUntil(
    // caches.open() создаёт новый кэш с именем CACHE_NAME
    caches.open(CACHE_NAME).then((cache) => {
      // cache.addAll() загружает и сохраняет все файлы из массива ASSETS в этот кэш.
      // Если хотя бы один файл не скачается - install целиком провалится.
      // Если это обновление, старый воркер в это время продолжает обслуживать открытые страницы.
      return cache.addAll(ASSETS);
    }).then(() => {
      // Только когда все файлы успешно скачались...
      console.log('[Service Worker] Ресурсы успешно закэшированы в:', CACHE_NAME);
      // срабатывает метод self.skipWaiting(), который разрешает
      // новому воркеру включиться сразу, не дожидаясь закрытия
      // всех вкладок сайта (если они были открыты).
      // Без этого новый воркер застрял бы в ожидании,
      // а событие 'activate' и очистка старого кэша не начались бы,
      // пока пользователь не закроет все страницы приложения.
      return self.skipWaiting(); // 🧀
    })
  );
});

/* ===========================💮💮💮=========================== */
// Событие 'activate' - срабатывает после install, когда старый
// воркер уходит, а новый успешно занимает его место.
// Здесь мы очищаем старые кэши именно этого приложения,
// чтобы не хранить мёртвые данные и не раздувать хранилище.
// ---------------------------------------------------------------
self.addEventListener('activate', (event) => {
  console.log('[Service Worker] Воркер успешно активирован (Activate)!');
  // event.waitUntil() - говорит браузеру: «подожди, пока я закончу уборку,
  // не закрывай воркер, пока удаляются старые файлы»
  event.waitUntil(
    // caches.keys() возвращает массив имён всех кэшей на этом домене (Origin).
    caches.keys().then((cacheNames) => {
      return Promise.all(
        cacheNames.map((cache) => {
          // Безопасная проверка: удаляем кэш только если он принадлежит 
          // текущему приложению и его версия отлична от актуальной версии.
          if (cache.startsWith(CACHE_PREFIX) && cache !== CACHE_NAME) {
            console.log('[Service Worker] Удалён старый кэш этого приложения:', cache);
            return caches.delete(cache);
          }
          // Кэши других проектов это условие просто проигнорируют.
        })
      );
    }).then(() => {
      // Метод self.clients.claim() заставляет воркер мгновенно взять под контроль 
      // все открытые вкладки приложения прямо сейчас, без перезагрузки страницы.
      // Теперь при любом следующем запросе или обновлении страницы пользователем 
      // файлы гарантированно и без задержек начнут отдаваться из нового кэша.
      return self.clients.claim(); // 🧀
    })
  );
});

/* ===========================💮💮💮=========================== */
// Событие 'fetch' - срабатывает при каждом сетевом запросе из приложения
// (загрузка HTML, CSS, JS, JSON, шрифтов, картинок и т.д.).
// Здесь мы решаем: отдать файл из кэша или пойти за ним в сеть.
// Главный инструмент, который обеспечивает работу приложения в офлайне.
// ---------------------------------------------------------------
self.addEventListener('fetch', (event) => {
  console.log('[Service Worker] Перехват запроса (Fetch):', event.request.url);
  // event.respondWith() - говорит браузеру: «подожди идти в интернет,
  // дай я сам решу, откуда выдать этот файл - из кэша или из сети»
  event.respondWith(
    // caches.match() ищет в сохранённом кэше файл, который соответствует текущему запросу
    caches.match(event.request).then((cachedResponse) => {
      // Если файл нашли в кэше - мгновенно отдаём его (это работает быстро и без интернета)
      if (cachedResponse) {
        console.log('[Service Worker] Ресурс взят из кэша:', event.request.url);
        return cachedResponse;
      }
      // Если файла в кэше нет - идём за ним напрямую в сеть через fetch()
      console.log('[Service Worker] Запрос ушел в сеть:', event.request.url);
      return fetch(event.request);
    })
  );
});
